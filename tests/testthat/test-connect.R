test_that("db_connect dispatches on the argument", {
  skip_if_no_sqlite()
  con <- db_connect(fakehosp_path())
  expect_s4_class(con, "SQLiteConnection")
  expect_identical(db_connect(con), con)
  DBI::dbDisconnect(con)
  expect_error(db_connect(1), "must be")
  skip_if(requireNamespace("odbc", quietly = TRUE))
  expect_error(db_connect("Driver={x};Server=y;"), "odbc")
  expect_error(db_connect("MyDSN"), "odbc")
})

test_that("parquet_plan maps directories to schemas and part directories to tables", {
  root <- withr::local_tempdir()
  touch <- function(...) { f <- file.path(root, ...); dir.create(dirname(f), recursive = TRUE, showWarnings = FALSE); file.create(f) }
  touch("layer1", "pas_patients.parquet")
  touch("layer1", "pas_adt_events", "fy2022.parquet")
  touch("layer1", "pas_adt_events", "fy2023.parquet")
  touch("reference", "sites.parquet")
  touch("answers", "truth", "spells.parquet")
  touch("top.parquet")
  touch("readme.md")
  touch("answers", "truth", "stays.parquet")
  same <- function(files) all(grepl("^fy\\d{4}", basename(files)))
  plan <- DBinventory:::parquet_plan(root, same)
  key <- paste(plan$schema, plan$table)
  expect_setequal(key, c("layer1 pas_patients", "layer1 pas_adt_events", "reference sites", "answers_truth spells", "answers_truth stays", "main top"))
  naive <- DBinventory:::parquet_plan(root)
  expect_true("layer1_pas_adt_events fy2022" %in% paste(naive$schema, naive$table))
  expect_match(plan$source[plan$table == "pas_adt_events"], "pas_adt_events/\\*\\.parquet$")
  expect_match(plan$source[plan$table == "sites"], "sites\\.parquet$")
  single <- DBinventory:::parquet_plan(file.path(root, "top.parquet"))
  expect_equal(single$schema, "main")
  expect_equal(single$table, "top")
})

test_that("parquet_connect exposes views DuckDB can profile", {
  skip_if_not_installed("duckdb")
  root <- withr::local_tempdir()
  dir.create(file.path(root, "ref"))
  dcon <- DBI::dbConnect(duckdb::duckdb())
  DBI::dbExecute(dcon, sprintf("COPY (SELECT i AS id, 'x' || (i %% 3) AS code, CAST(DATE '2024-01-01' + INTERVAL (i) DAY AS DATE) AS d FROM range(1, 51) t(i)) TO '%s' (FORMAT PARQUET)", file.path(root, "ref", "codes.parquet")))
  DBI::dbExecute(dcon, sprintf("COPY (SELECT i AS id, i * 1.5 AS v FROM range(1, 11) t(i)) TO '%s' (FORMAT PARQUET)", file.path(root, "measures.parquet")))
  DBI::dbDisconnect(dcon, shutdown = TRUE)

  con <- parquet_connect(root)
  withr::defer(DBI::dbDisconnect(con, shutdown = TRUE))
  expect_equal(db_dialect(con)$name, "duckdb")
  tabs <- db_tables(con)
  expect_setequal(paste(tabs$table_schema, tabs$table_name), c("ref codes", "main measures"))
  inv <- db_inventory(con, progress = FALSE)
  expect_equal(inv$tables$row_count[inv$tables$table_name == "codes"], 50)
  expect_equal(inv$tables$newest_datetime[inv$tables$table_name == "codes"], "2024-02-20")
  prof <- db_profile(con, inv, sample_rows = 20, progress = FALSE)
  codes <- prof[prof$table_name == "codes", ]
  expect_true(all(codes$sampled))
  expect_equal(unique(codes$sample_method), "reservoir")
  expect_equal(codes$distinct_count[codes$column_name == "code"], 3)
  expect_equal(codes$semantic_type[codes$column_name == "code"], "code")
  full <- db_profile(con, inv, progress = FALSE)
  expect_true(full$is_unique[full$table_name == "measures" & full$column_name == "id"])
  expect_equal(full$mean_value[full$table_name == "measures" & full$column_name == "v"], 8.25)
})
