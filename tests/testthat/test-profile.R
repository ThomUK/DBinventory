test_that("semantic inference on the synthetic trust is sensible", {
  con <- fixture_con()
  inv <- db_inventory(con, include = c("pas_patients$", "endo_procedures", "derived_spells"), progress = FALSE)
  prof <- db_profile(con, inv, progress = FALSE)
  sem <- function(tab, col) prof$semantic_type[prof$table_name == tab & prof$column_name == col]
  expect_equal(sem("pas_patients", "mrn"), "identifier")
  expect_equal(sem("pas_patients", "sex"), "code")
  expect_equal(sem("pas_patients", "dob"), "date")
  expect_equal(sem("pas_patients", "ethnicity"), "code")
  expect_false(prof$values_suppressed[prof$table_name == "pas_patients" & prof$column_name == "ethnicity"])
  expect_equal(sem("pas_patients", "nhs_number_status"), "constant")   # one value in the 200-row fixture
  expect_equal(sem("endo_procedures", "ProcDate"), "date")      # a date stored as text
  expect_equal(sem("endo_procedures", "StartTime"), "time")
  expect_equal(sem("endo_procedures", "Report"), "free_text")
  expect_equal(sem("derived_spells", "emergency"), "flag")
  expect_equal(sem("derived_spells", "speldur"), "count")
})

test_that("a failing table is logged and the rest continue", {
  con <- toy_con()
  DBI::dbExecute(con, "CREATE TABLE gone (x INTEGER)")
  DBI::dbExecute(con, "CREATE VIEW broken AS SELECT * FROM gone")
  DBI::dbExecute(con, "DROP TABLE gone")
  inv <- db_inventory(con, include = c("toy$", "broken"), progress = FALSE)
  store <- withr::local_tempfile(fileext = ".sqlite")
  expect_message(prof <- db_profile(con, inv, store = store, progress = FALSE), "Profile failed")
  expect_equal(unique(prof$table_name), "toy")
  st <- store_open(store)
  log <- store_read(st, "profile_log")
  store_close(st)
  expect_equal(log$status[log$table_name == "broken"], "error")
  expect_equal(log$status[log$table_name == "toy"], "ok")
})

