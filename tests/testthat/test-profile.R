test_that("db_profile computes exact statistics on a toy table", {
  con <- toy_con()
  inv <- db_inventory(con, include = "^main\\.toy$", progress = FALSE)
  prof <- db_profile(con, inv, progress = FALSE, keep_values = TRUE)
  expect_s3_class(prof, "column_profile")
  expect_equal(nrow(prof), 8)
  expect_false(any(prof$sampled))
  expect_equal(unique(prof$rows_profiled), 30)
  row <- function(col) prof[prof$column_name == col, ]

  id <- row("id")
  expect_equal(id$null_count, 0)
  expect_equal(id$distinct_count, 30)
  expect_true(id$is_unique)
  expect_equal(id$min_value, "1")
  expect_equal(id$max_value, "30")
  expect_equal(id$mean_value, 15.5)
  expect_equal(id$semantic_type, "identifier")

  code <- row("code")
  expect_equal(code$distinct_count, 3)
  expect_equal(code$empty_count, 10)
  expect_equal(code$mean_length, 2 / 3)
  expect_equal(code$semantic_type, "code")
  tv <- top_values_of(prof, "toy", "code")
  expect_setequal(tv$value, c("A", "B", ""))
  expect_equal(tv$n, c(10, 10, 10))

  flag <- row("flag")
  expect_equal(flag$true_count, 15)
  expect_equal(flag$semantic_type, "flag")
  expect_true(is.na(flag$min_value))

  amount <- row("amount")
  expect_equal(amount$null_count, 6)
  expect_equal(amount$null_rate, 0.2)
  expect_equal(amount$mean_value, 22.5)
  expect_equal(amount$semantic_type, "measure")

  seen <- row("seen")
  expect_equal(seen$null_count, 1)
  expect_equal(seen$min_value, "2024-01-02 10:00:00")
  expect_equal(seen$max_value, "2024-01-31 10:00:00")
  expect_equal(seen$semantic_type, "datetime")

  note <- row("note")
  expect_equal(note$null_count, 4)
  expect_true(note$mean_length > 30)
  expect_equal(note$semantic_type, "free_text")

  blank <- row("blank")
  expect_equal(blank$null_rate, 1)
  expect_equal(blank$semantic_type, "empty")
  expect_true(is.na(blank$top_values))

  nhs <- row("nhs_number")
  expect_equal(nhs$distinct_count, 29)
  expect_true(nhs$is_unique)
  expect_false(nhs$pk_candidate)        # unique but has a null
  expect_true(id$pk_candidate)
  expect_false(row("seen")$pk_candidate) # datetimes are not key material
  expect_false(code$pk_candidate)
  expect_equal(nhs$semantic_type, "identifier")
  expect_equal(nhs$min_length, 10)

  expect_true(all(nchar(prof$value_fingerprint) == 16))
  expect_false(any(prof$values_suppressed))
})

test_that("sensitive values are suppressed by default but hashes survive", {
  con <- toy_con()
  inv <- db_inventory(con, include = "^main\\.toy$", progress = FALSE)
  open <- db_profile(con, inv, progress = FALSE, keep_values = TRUE)
  shut <- db_profile(con, inv, progress = FALSE)
  nhs <- shut[shut$column_name == "nhs_number", ]
  expect_true(nhs$values_suppressed)
  expect_true(is.na(nhs$min_value) && is.na(nhs$max_value) && is.na(nhs$top_values))
  expect_false(is.na(nhs$top_values_hash))
  expect_equal(nhs$value_fingerprint, open$value_fingerprint[open$column_name == "nhs_number"])
  expect_true(shut$values_suppressed[shut$column_name == "note"])
  expect_false(shut$values_suppressed[shut$column_name == "code"])
  expect_false(is.na(shut$min_value[shut$column_name == "seen"]))
})

test_that("large tables are sampled through a temporary table", {
  con <- fixture_con()
  inv <- db_inventory(con, include = "pas_adt_events", progress = FALSE)
  prof <- db_profile(con, inv, sample_rows = 50, progress = FALSE)
  expect_true(all(prof$sampled))
  expect_equal(unique(prof$sample_method), "random_order")
  expect_equal(unique(prof$rows_profiled), 50)
  expect_equal(unique(prof$row_count), 200)
  expect_false(any(grepl("^dbinv_", DBI::dbListTables(con))))
  full <- db_profile(con, inv, sample_rows = Inf, progress = FALSE)
  expect_false(any(full$sampled))
  expect_equal(unique(full$rows_profiled), 200)
})

