test_that("duplicate_candidates finds the same column in two tables", {
  con <- fixture_con()
  inv <- db_inventory(con, include = c("pas_adt_events", "derived_ward_stays", "derived_spells"), progress = FALSE)
  prof <- db_profile(con, inv, progress = FALSE)
  dup <- duplicate_candidates(prof)
  expect_s3_class(dup, "tbl_df")
  expect_named(dup, c("fingerprint", "n_columns", "n_tables", "columns"))
  expect_true(all(dup$n_tables > 1))
  strict <- duplicate_candidates(prof, by = "column_fingerprint")
  expect_true(nrow(strict) <= nrow(dup))
  none <- duplicate_candidates(prof[1, ])
  expect_equal(nrow(none), 0)
})
